<section id="who-we-are">
  <h2>1. Who we are</h2>
  <p>
    IdleWheels ("we", "us") runs this website, a marketplace in Ghana where car owners ("hosts") rent out their cars to other people ("renters") by the day.
    We are responsible for the personal data described in this policy and handle it in line with the Data Protection Act, 2012 (Act 843) of Ghana.
  </p>
  <p>This policy explains what we collect when you use IdleWheels, why we collect it, who can see it and what you can ask us to do with it.</p>
</section>

<section id="what-we-collect">
  <h2>2. What we collect</h2>
  <h3>When you create an account</h3>
  <ul>
    <li>Your name, email address and, if you add it, your phone number.</li>
    <li>Your password. We only store it in a scrambled (hashed) form, so nobody at IdleWheels can read it.</li>
  </ul>
  <h3>When you book a car</h3>
  <ul>
    <li>The car, your pick-up and return dates, any extras you add and the price you pay.</li>
    <li>The phone number you give for the booking and any note you write to the host.</li>
    <li>Payment records: the amount, the payment reference and whether you paid by card or mobile money. We never see or store your card number or mobile money PIN.</li>
  </ul>
  <h3>When you host a car</h3>
  <ul>
    <li>Your host application: display name, phone number, city or area, a short description about you and your payout details (mobile money number or bank account).</li>
    <li>Your car listings: make, model, year, specs, location, daily price, description and the photos you upload.</li>
  </ul>
  <h3>Other things you send us</h3>
  <ul>
    <li>Reviews you write after a rental.</li>
    <li>Cars you save to your account.</li>
    <li>Messages you send through our contact form, including your name, email, phone number and booking reference if you add them.</li>
  </ul>
  <h3>Collected automatically</h3>
  <ul>
    <li>A session cookie that keeps you logged in (see section 9).</li>
    <li>Basic server logs kept by our web host, such as IP address, browser type and the pages requested, used to keep the site running and secure.</li>
  </ul>
</section>

<section id="how-we-use">
  <h2>3. How we use your information</h2>
  <ul>
    <li>To create and run your account and let you log in.</li>
    <li>To review host applications and car listings before they go live.</li>
    <li>To take bookings and payments, and to handle cancellations and refunds.</li>
    <li>To put hosts and renters in touch so they can arrange the hand-over.</li>
    <li>To show reviews that help other renters choose a car.</li>
    <li>To work out and pay host earnings.</li>
    <li>To answer your messages and help with problems.</li>
    <li>To keep the site secure and prevent fraud or misuse.</li>
  </ul>
  <p>
    We use your data because we need it to provide the service you signed up for, because the law requires it (for example, keeping payment records),
    or because we have a legitimate interest in running a safe and reliable marketplace. We do not send marketing emails.
  </p>
</section>

<section id="sharing-bookings">
  <h2>4. What hosts and renters can see</h2>
  <p>To make a rental happen, we share only what is needed between the two people involved:</p>
  <ul>
    <li><strong>The host</strong> sees the renter's name, email address, booking phone number, note and the booking details.</li>
    <li><strong>The renter</strong> sees the host's display name and, once the booking is confirmed, the host's phone number and the car's location.</li>
  </ul>
  <p>
    Hosts and renters may only use each other's details for that booking. Your car listings are public, and reviews you write show your first name and the
    first letter of your last name.
  </p>
</section>

<section id="payments">
  <h2>5. Payments</h2>
  <p>
    Card and mobile money payments are handled by Paystack, our payment provider. You enter your payment details on Paystack's secure checkout page, not on
    IdleWheels. Paystack tells us whether the payment succeeded, the amount and the payment method. Paystack processes your payment details under
    its own privacy policy, which you can read on paystack.com.
  </p>
</section>

<section id="other-sharing">
  <h2>6. Who else we share data with</h2>
  <p>We do not sell your personal data. Apart from Paystack, we only share it with:</p>
  <ul>
    <li>our web hosting provider, which stores the website and its database;</li>
    <li>the police or other authorities, when the law requires it or when someone's safety is at risk.</li>
  </ul>
</section>

<section id="retention">
  <h2>7. How long we keep it</h2>
  <ul>
    <li>Account details are kept while your account is open.</li>
    <li>Booking and payment records are kept for six years after the booking, because we need them for accounting and tax purposes and to deal with any disputes.</li>
    <li>Contact form messages are kept for one year.</li>
    <li>Car photos are deleted when the host removes them or the listing is deleted.</li>
  </ul>
  <p>After these periods we delete the data or make it anonymous.</p>
</section>

<section id="your-rights">
  <h2>8. Your rights</h2>
  <p>Under the Data Protection Act, 2012 (Act 843) you can:</p>
  <ul>
    <li>ask whether we hold data about you and get a copy of it;</li>
    <li>correct details that are wrong or out of date (you can change your name, phone number and password yourself under My account);</li>
    <li>ask us to delete your data, except records we must keep by law;</li>
    <li>object to how we use your data;</li>
    <li>complain to the Data Protection Commission of Ghana.</li>
  </ul>
  <p>To make a request, send us a message through our <a href="<?= url('/contact') ?>">contact page</a>. We may ask you to confirm your identity first, and we will reply within 30 days.</p>
</section>

<section id="cookies">
  <h2>9. Cookies</h2>
  <p>
    IdleWheels uses one cookie, <code>idlewheels_session</code>. It keeps you logged in and protects forms from misuse while you browse, and it is deleted
    when you close your browser or log out. We do not use advertising or tracking cookies. If you block cookies, you will not be able to log in.
  </p>
</section>

<section id="security">
  <h2>10. Security</h2>
  <p>
    We protect your data by storing passwords in hashed form, checking every form submission, limiting uploads to image files and restricting access to the
    admin area. Payments are handled entirely on Paystack's secure checkout. No website is completely secure, but if a breach affects your personal data we will
    tell you and the Data Protection Commission as the law requires.
  </p>
</section>

<section id="children">
  <h2>11. Age limit</h2>
  <p>
    You must be at least 21 to use IdleWheels. We do not knowingly collect data from anyone under 21. If you think someone under 21 has created an account, let us know
    and we will delete it.
  </p>
</section>

<section id="changes">
  <h2>12. Changes to this policy</h2>
  <p>If we change this policy, we will post the new version on this page and update the date at the top.</p>
</section>

<section id="contact">
  <h2>13. Contact us</h2>
  <p>For any question about your privacy or this policy, send us a message through our <a href="<?= url('/contact') ?>">contact page</a> and choose "Something else".</p>
</section>
